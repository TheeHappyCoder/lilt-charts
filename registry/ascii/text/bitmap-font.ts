/**
 * The text in the bitmap font as a field of ink, `P` samples a square unit across a `width` by
 * `height` area, fitted to the box `fit` gives and centred.
 */
export function bitmapInk(
  text: string,
  width: number,
  height: number,
  P: number,
  fit: (width: number, height: number) => { w: number; h: number },
): Float32Array {
  const glyphs = Array.from(text.toUpperCase()).map((ch) => FONT[ch] ?? FONT['?']!);
  // Five columns a letter and one between.
  const unitsW = glyphs.length * 6 - 1;
  const unitsH = 7;
  const box = fit(width, height);
  const unit = Math.min(box.w / unitsW, box.h / unitsH);
  const left = (width - unitsW * unit) / 2;
  const top = (height - unitsH * unit) / 2;
  const w = Math.ceil(width * P);
  const h = Math.ceil(height * P);
  const ink = new Float32Array(w * h);
  for (let py = 0; py < h; py++) {
    const v = Math.floor(((py + 0.5) / P - top) / unit);
    if (v < 0 || v >= unitsH) continue;
    for (let px = 0; px < w; px++) {
      const u = Math.floor(((px + 0.5) / P - left) / unit);
      if (u < 0 || u >= unitsW || u % 6 === 5) continue;
      if (glyphs[Math.floor(u / 6)]![v]![u % 6] === '1') ink[py * w + px] = 1;
    }
  }
  return ink;
}
