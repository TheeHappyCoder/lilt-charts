/** The page a pathname belongs to; a nested page such as an API topic belongs to its parent. */
export function routeFor(pathname: string): AppRoute {
  return (appRoutes.find((route) => route.pathname === pathname) ??
    appRoutes.find((route) => pathname.startsWith(`${route.pathname}/`)) ??
    appRoutes.find((route) => route.id === 'area')!) as AppRoute;
}
